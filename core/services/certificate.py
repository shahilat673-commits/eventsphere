from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.pdfgen import canvas


def build_certificate(ticket, name):
    ev = ticket.event
    buf = BytesIO()
    w, h = landscape(A4)
    c = canvas.Canvas(buf, pagesize=landscape(A4))
    c.setStrokeColor(colors.HexColor('#C6613F')); c.setLineWidth(6); c.rect(25, 25, w - 50, h - 50)
    c.setLineWidth(1.5); c.rect(38, 38, w - 76, h - 76)
    c.setFillColor(colors.HexColor('#C6613F')); c.setFont('Helvetica-Bold', 34)
    c.drawCentredString(w / 2, h - 110, 'CERTIFICATE OF PARTICIPATION')
    c.setFillColor(colors.black); c.setFont('Helvetica', 16)
    c.drawCentredString(w / 2, h - 165, 'This is to certify that')
    c.setFont('Helvetica-Bold', 30); c.drawCentredString(w / 2, h - 220, name)
    c.setFont('Helvetica', 16)
    c.drawCentredString(w / 2, h - 265, 'has successfully participated in')
    c.setFont('Helvetica-Bold', 22); c.drawCentredString(w / 2, h - 305, ev.title)
    c.setFont('Helvetica', 14)
    c.drawCentredString(w / 2, h - 340, f'held on {ev.start:%d %B %Y} at {ev.venue}, {ev.city}')
    c.setFont('Helvetica-Oblique', 12)
    c.drawString(80, 90, f'Organised by: {ev.organiser.organisation or ev.organiser.display_name}')
    c.drawRightString(w - 80, 90, f'Certificate ID: {ticket.code[:12].upper()}')
    c.setFont('Helvetica', 10); c.setFillColor(colors.grey)
    c.drawCentredString(w / 2, 55, 'Generated by EventSphere AI  |  Plan it. Book it. Live it.')
    c.showPage(); c.save()
    return buf.getvalue()
